"""Template-based draft paperwork. Output sirf DRAFT hai -- court staff review ke baad hi use ho."""
from .models import Case, Hearing

DISCLAIMER = "[DRAFT - generated by Sub-Judice. To be reviewed by authorised court staff before use.]"


def _header(case: Case, hearing: Hearing) -> str:
    when = hearing.scheduled_at.strftime("%d %B %Y, %I:%M %p")
    return (
        f"{DISCLAIMER}\n\n"
        f"Case No.: {case.case_number}\n"
        f"Title: {case.title}\n"
        f"Filed by: {case.filer_name} ({case.filer_type})\n"
        f"Court: {hearing.court or 'To be confirmed'}\n"
        f"Hearing date: {when}\n"
    )


def render(doc_type: str, case: Case, hearing: Hearing, prepared_by: str | None) -> str:
    head = _header(case, hearing)
    purpose = hearing.purpose or "hearing"
    sign = f"\nPrepared by: {prepared_by or '________________'}\n"

    if doc_type == "hearing_notice":
        body = (
            f"\nNOTICE OF HEARING\n\nTake notice that the above matter is listed for {purpose} "
            f"on the date and time stated above. All parties are required to appear with relevant "
            f"documents and evidence.\n"
        )
    elif doc_type == "summons":
        body = (
            f"\nSUMMONS\n\nYou are hereby summoned to appear before the court on the date stated above "
            f"in the matter of '{case.title}'. Failure to appear may result in proceedings in your absence.\n"
        )
    elif doc_type == "adjournment_application":
        body = (
            f"\nAPPLICATION FOR ADJOURNMENT\n\nThe applicant respectfully requests that the hearing listed "
            f"for {purpose} be adjourned for the following reasons:\n\n1. ________________\n2. ________________\n"
        )
    else:  # order_sheet
        body = (
            f"\nORDER SHEET\n\nMatter listed for {purpose}.\nPresent: ________________\n"
            f"Proceedings: ________________\nNext date: ________________\n"
        )
    return head + body + sign
